    <h2 id="landing-questions-title">Before you sign in.</h2>
    <div class="landing-faqs">
        <details open>
            <summary>What is alumni tracing?</summary>
            <p>Alumni tracing is the process of keeping in touch with graduates and understanding their employment outcomes after graduation. It helps connect academic experiences with the journeys that follow.</p>
        </details>
        <details>
            <summary>What information does Alumni Tracer organize?</summary>
            <p>The platform brings together alumni contact details, academic programs, graduation dates, employment status, and tracing notes. Records can also include education and employment histories.</p>
        </details>
        <details>
            <summary>Can the team import existing alumni records?</summary>
            <p>Yes. The Alumni Directory includes an Excel import and a downloadable template to help your team bring existing records into the platform.</p>
        </details>
        <details>
            <summary>Can alumni reports be downloaded?</summary>
            <p>Yes. The Alumni Data Report can be filtered by graduation year, program, and employment status, then downloaded as an Excel workbook.</p>
        </details>
    </div>
</section>
